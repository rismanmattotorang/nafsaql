"""Generate docs/publication/gen/results.tex from stored evidence (P6-T03: every number traceable to a run).
Reads the running gateway's API and the evidence files; each table names its source run IDs.
Usage: python3 -I scripts/gen_publication.py [--base http://127.0.0.1:8080]"""
import json, os, sys, urllib.request
ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
BASE = sys.argv[sys.argv.index("--base") + 1] if "--base" in sys.argv else "http://127.0.0.1:8080"
get = lambda p: json.load(urllib.request.urlopen(BASE + p, timeout=120))
rd = lambda p: json.load(open(os.path.join(ROOT, p))) if os.path.exists(os.path.join(ROOT, p)) else None
tex = lambda s: str(s).replace("_", r"\_").replace("%", r"\%").replace("&", r"\&").replace("#", r"\#")
pc = lambda x: "--" if x is None else f"{100 * x:.0f}\\%"
out = ["% Generated by scripts/gen_publication.py; do not edit."]
# Scaled Phase-2 evaluation
runs = get("/v1/eval/runs")
p2 = next((r for r in runs if r["request"]["benchmark"] == "smoke_mixed" and "nafs_blind" in r["request"]["systems"]), None)
if p2:
    r = get(f"/v1/eval/runs/{p2['run_id']}")
    rows = "\n".join(f"{tex(k)} & {v['n_scored']} & {pc(v['accuracy'])} & [{pc(v['accuracy_ci95'][0])}, {pc(v['accuracy_ci95'][1])}] & {pc(v['escalation_rate'])} & {v['mean_wall_ms'] / 1000:.0f} \\\\" for k, v in r["systems"].items())
    out.append(r"\newcommand{\PhaseTwoRun}{\texttt{" + p2["run_id"][:8] + "}}")
    out.append(r"\newcommand{\PhaseTwoTable}{\begin{tabular}{lrrrrr}\toprule System & $n$ & Acc. & 95\% CI & Esc. & Wall (s)\\\midrule " + rows + r" \bottomrule\end{tabular}}")
    rt = r.get("routing", {}).get("nafs_blind", {})
    out.append(r"\newcommand{\BlindRouting}{" + pc(rt.get("routing_accuracy")) + "}")
    cr = next((p for p in r["paired"] if p["a"] == "nafs_aql" and p["b"] == "slow_only"), {})
    out.append(r"\newcommand{\GatedCostRatio}{" + (f"{cr['cost_ratio']:.2f}" if cr.get("cost_ratio") else "--") + "}")
# Verifier quality
rates = get("/v1/verifiers")["rates"]
vr = "\n".join(f"{tex(k)} & {v['n_correct']} & {v['r']:.3f} & {v['n_mutants']} & {v['phi']:.3f} & {v['phi_upper95']:.3f} \\\\" for k, v in sorted(rates.items()) if k != "math_symbolic")
out.append(r"\newcommand{\VerifierTable}{\begin{tabular}{lrrrrr}\toprule Verifier & Correct & $r$ & Mutants & $\varphi$ & $\varphi$ upper \\\midrule " + vr + r" \bottomrule\end{tabular}}")
out.append(r"\newcommand{\RatesRuns}{" + ", ".join(r"\texttt{" + x["run_id"][:8] + "}" for x in get("/v1/verifiers/runs") if x["status"] == "done") + "}")
# Load-test protocol
prot = [b for b in get("/v1/bench/runs") if b.get("kind") == "protocol" and b["status"] == "done" and b.get("table")]
if prot:
    b = prot[0]
    pr = "\n".join(f"{t['concurrency']} & {t['p50_ms'] / 1000:.1f} & {t['p95_ms'] / 1000:.1f} & {t['p99_ms'] / 1000:.1f} & {t['throughput_rps']:.2f} \\\\" for t in b["table"])
    out.append(r"\newcommand{\ProtocolRun}{\texttt{" + b["run_id"][:8] + "}}")
    out.append(r"\newcommand{\ProtocolTable}{\begin{tabular}{rrrrr}\toprule Sessions & p50 (s) & p95 (s) & p99 (s) & req/s\\\midrule " + pr + r" \bottomrule\end{tabular}}")
    out.append(r"\newcommand{\NfrSevenRatio}{" + f"{b['nfr007']['ratio']:.2f}" + "}")
    out.append(r"\newcommand{\NProtocolRuns}{" + str(len(prot)) + "}")
# Regression baseline (fast path)
reg = next((r for r in runs if r["request"]["benchmark"] == "regression_500" and r["progress"]["done"] > 50), None)
if reg:
    r = get(f"/v1/eval/runs/{reg['run_id']}")
    s = r["systems"]["fast_only"]
    out.append(r"\newcommand{\RegressionRun}{\texttt{" + reg["run_id"][:8] + "}}")
    out.append(r"\newcommand{\RegressionSummary}{" + f"{s['n_scored']} items scored ({r['status']}), fast-path accuracy {pc(s['accuracy'])} [{pc(s['accuracy_ci95'][0])}, {pc(s['accuracy_ci95'][1])}], mean wall {s['mean_wall_ms'] / 1000:.1f}\\,s" + "}")
# Profile C, security, deployment, gates
pcd = rd("benchmarks/profile_c_decision.json")
out.append(r"\newcommand{\ProfileCDecision}{" + tex(pcd["decision"] if pcd else "pending") + "}")
if pcd and "accuracy" in pcd:
    rows = "\n".join(f"{tex(k)} & {pc(v['all'])} & {pc(v.get('math'))} & {pc(v.get('code'))} & {pc(v.get('structured'))} & {pcd['mean_wall_s'][k]:.1f} & {pcd['tokens_per_s'][k]:.1f} \\\\" for k, v in pcd["accuracy"].items())
    out.append(r"\newcommand{\ProfileCTable}{\begin{tabular}{lrrrrrr}\toprule System 1 & All & Math & Code & JSON & Wall (s) & tok/s\\\midrule " + rows + r" \bottomrule\end{tabular}}")
    out.append(r"\newcommand{\ProfileCDelta}{" + f"{100 * pcd['paired_delta_accuracy']:+.0f} points, 95\\% CI [{100 * pcd['ci95'][0]:+.0f}, {100 * pcd['ci95'][1]:+.0f}], $n={pcd['n_tasks']}$" + "}")
# P7-T01: where the time goes (all replies with stage timings, lab runs included)
st = get("/v1/perf/stages?hours=2160&lab=true")
names = {"draft": "System 1 draft", "sample": "cheap samples", "verify_draft": "verify draft", "deliberate": "System 2 deliberation", "verify": "verify", "judge": "judge", "retrieval": "retrieval"}
rows = []
for pth in st.get("paths", []):
    for x in pth["stages"]:
        if x["share"] is not None and x["share"] >= 0.001:
            rows.append(f"{'fast' if pth['mode'] == 'fast' else 'deliberate'} ({pth['replies']}) & {tex(names.get(x['stage'], x['stage']))} & {pc(x['share'])} & {x['p50_ms'] / 1000:.1f} & {x['p95_ms'] / 1000:.1f} \\\\")
out.append(r"\newcommand{\StageTable}{\begin{tabular}{llrrr}\toprule Path (replies) & Stage & Share & p50 (s) & p95 (s)\\\midrule " + ("\n".join(rows) or r"\multicolumn{5}{c}{no data} \\\\") + r" \bottomrule\end{tabular}}")
eng = "\n".join(f"{tex(names.get(e['stage'], e['stage']))} & {e['calls']} & {e['prefill_tok_s'] or 0:.0f} & {e['decode_tok_s'] or 0:.1f} & {pc(e['cache_reuse'])} \\\\" for e in st.get("engine", []))
out.append(r"\newcommand{\EngineTable}{\begin{tabular}{lrrrr}\toprule Model stage & Calls & Prefill tok/s & Decode tok/s & Cache reuse\\\midrule " + (eng or r"\multicolumn{5}{c}{no data} \\\\") + r" \bottomrule\end{tabular}}")
out.append(r"\newcommand{\StageReplies}{" + str(st.get("replies", 0)) + "}")
# P7-T03: early escalation study
ee = rd("benchmarks/early_escalation_study.json")
if ee:
    g = [x for x in ee["grid"] if x["n_min"] in (32, 48) and x["margin"] in (0.0, 0.02, 0.04, 0.15)]
    rows = "\n".join(f"{x['n_min']} & {x['margin']:.2f} & {pc(x['agreement'])} & {x['caught_early']}/{x['full_escalations']} & {x['false_early']} & {x['tokens_saved_per_escalation']:.0f} \\\\" for x in g)
    out.append(r"\newcommand{\EarlyEscTable}{\small\begin{tabular}{rrrrrr}\toprule $N$ & Margin & Agreement & Caught & False & Saved tok/esc.\\\midrule " + rows + r" \bottomrule\end{tabular}}")
    c = ee["configured"]
    out.append(r"\newcommand{\EarlyEscSummary}{" + f"on {c['n']} open-ended prompts, the configured rule ($N={c['n_min']}$, margin {c['margin']:.2f}) agreed with the full-draft decision on {pc(c['agreement'])} of prompts, caught {c['caught_early']} of {c['full_escalations']} escalations early and saved {c['tokens_saved_per_escalation']:.0f} draft tokens per early escalation" + "}")
else:
    out.append(r"\newcommand{\EarlyEscTable}{\emph{pending: the study is running}}")
    out.append(r"\newcommand{\EarlyEscSummary}{pending}")
sec = rd("docs/security/security_review.json")
out.append(r"\newcommand{\SecuritySummary}{" + (f"{sec['tests_passed']}/{sec['tests_total']} security tests pass; {sec['open_high_or_above']} open high-severity findings" if sec else "pending") + "}")
dep = rd("deploy/verified.json")
out.append(r"\newcommand{\DeploySummary}{" + tex(dep["summary"] if dep else "pending") + "}")
gates = get("/v1/gates")["gates"]
out.append(r"\newcommand{\GatesTable}{\begin{tabular}{llp{9cm}}\toprule Gate & Status & Evidence\\\midrule " + "\n".join(
    f"{g['gate']} & {g['status']} & {tex('; '.join(c['id'] + ': ' + c['status'] for c in g['criteria']))} \\\\" for g in gates) + r" \bottomrule\end{tabular}}")
# Lab policy map, summarised per domain as contiguous lambda ranges
ins = get("/v1/lab/insights")
NAME = {"fast": "System~1 alone", "gated": "the gate with the verifier", "blind": "the blind gate", "slow": "System~2 always"}
parts = []
for d in ins.get("domains", []):
    pm = [(round(x["lambda"], 2), x["policy"]) for x in d.get("policy_map", [])]
    if not pm:
        continue
    segs, cur = [], None
    for lam, pol in pm:
        if cur and cur[0] == pol:
            cur[2] = lam
        else:
            cur = [pol, lam, lam]; segs.append(cur)
    if len(segs) == 1:
        desc = f"{NAME.get(segs[0][0], segs[0][0])} at every $\\lambda$"
    else:
        desc = ", ".join(f"{NAME.get(p, p)} for $\\lambda\\le{hi:g}$" if i == 0 else (f"{NAME.get(p, p)} for $\\lambda\\ge{lo:g}$" if i == len(segs) - 1 else f"{NAME.get(p, p)} for ${lo:g}\\le\\lambda\\le{hi:g}$") for i, (p, lo, hi) in enumerate(segs))
    parts.append(f"{tex(d['domain'])}: {desc}")
out.append(r"\newcommand{\PolicyMapSummary}{" + ("; ".join(parts) or "no runs yet") + "}")
out.append(r"\newcommand{\PolicyMapRuns}{" + str(ins.get("runs", 0)) + "}")
# P7-T04: EAGLE-3 A/B; P7-T08: adaptive exit study (paired Lab run slow_only vs slow_noexit)
rows = []
for sysn in (1, 2):
    ab = rd(f"benchmarks/eagle3_ab_system{sysn}.json")
    if not ab:
        continue
    for k, v in ab["summary"].items():
        name, temp = k.split("/")
        rows.append(f"System~{sysn} & {tex(name)} & {temp} & {v['decode_tok_s']:.1f} & {v['speedup'] or 0:.2f} & {pc(v['acceptance'])} \\\\")
out.append(r"\newcommand{\EagleTable}{\begin{tabular}{llllrr}\toprule Model & Variant & Sampling & Decode tok/s & Speed-up & Drafted tokens accepted\\\midrule " + ("\n".join(rows) or r"\multicolumn{6}{c}{pending} \\\\") + r" \bottomrule\end{tabular}}")
ax = next((r for r in runs if r["request"]["benchmark"] == "gsm8k" and set(r["request"]["systems"]) == {"slow_only", "slow_noexit"} and r["status"] == "done"), None)
if ax:
    r = get(f"/v1/eval/runs/{ax['run_id']}")
    s1, s2 = r["systems"]["slow_only"], r["systems"]["slow_noexit"]
    pr = next((p for p in r.get("paired", []) if {p["a"], p["b"]} == {"slow_only", "slow_noexit"}), {})
    out.append(r"\newcommand{\AdaptiveExitRun}{\texttt{" + ax["run_id"][:8] + "}}")
    out.append(r"\newcommand{\AdaptiveExitSummary}{" + f"with the exit: accuracy {pc(s1['accuracy'])}, mean wall {s1['mean_wall_ms'] / 1000:.0f}\\,s; without: {pc(s2['accuracy'])}, {s2['mean_wall_ms'] / 1000:.0f}\\,s ($n={s1['n_scored']}$ GSM8K items" + (f"; paired $\\Delta$ accuracy {100 * pr['delta_accuracy']:+.0f} points, 95\\% CI [{100 * pr['ci95'][0]:+.0f}, {100 * pr['ci95'][1]:+.0f}]" if pr.get("ci95") else "") + ")}")
else:
    out.append(r"\newcommand{\AdaptiveExitRun}{pending}")
    out.append(r"\newcommand{\AdaptiveExitSummary}{pending}")
# P7-T10: vLLM backend check; P7-T05: weight formats; P7-T09: judge on System 1
vc = rd("benchmarks/vllm_check.json")
if vc:
    t = vc.get("timings_s", {})
    out.append(r"\newcommand{\VllmCheckSummary}{" + f"{vc['passed']} of {vc['passed'] + vc['failed']} checks passed" + (f"; fast verified reply {t['vllm_fast_s']:.0f}\\,s on vLLM against {t['llama_fast_s']:.0f}\\,s on llama-server, deliberate reply {t['vllm_slow_s']:.0f}\\,s against {t['llama_slow_s']:.0f}\\,s" if all(k in t for k in ("vllm_fast_s", "llama_fast_s", "vllm_slow_s", "llama_slow_s")) else "") + "}")
else:
    out.append(r"\newcommand{\VllmCheckSummary}{no result yet: on the day of the work the host had under 1\,GB free and the Docker VM did not start at the 7.5\,GiB the stand-in needs}")
import re as _re
qrows = {}
try:
    for line in open(os.path.join(ROOT, "logs/quant_ab.log")):
        m = _re.match(r"r(\d) (\S+) .*?(pp128|tg64) \|\s+([\d.]+) ± ([\d.]+)", line)
        if m:
            qrows.setdefault(m.group(2), {}).setdefault(m.group(3), []).append(float(m.group(4)))
except FileNotFoundError:
    pass
if qrows:
    rows = "\n".join(f"{tex(k.replace('.own', ' (own)'))} & {sum(v.get('pp128', [0])) / max(1, len(v.get('pp128', []))):.0f} & {sum(v.get('tg64', [0])) / max(1, len(v.get('tg64', []))):.1f} \\\\" for k, v in qrows.items())
    out.append(r"\newcommand{\QuantTable}{\begin{tabular}{lrr}\toprule Weights (Qwen3-1.7B) & Prefill tok/s & Decode tok/s\\\midrule " + rows + r" \bottomrule\end{tabular}}")
else:
    out.append(r"\newcommand{\QuantTable}{pending}")
js = rd("benchmarks/judge_system1_rates.json")
j1 = (js or {}).get("judge") or ((js or {}).get("rates") or {}).get("judge")
j2 = rates.get("judge")
out.append(r"\newcommand{\JudgeCompare}{" + (f"System~2 judge: $r={j2['r']:.2f}$, $\\varphi={j2['phi']:.3f}$ (upper {j2['phi_upper95']:.2f}); System~1 judge: $r={j1['r']:.2f}$, $\\varphi={j1['phi']:.2f}$ (upper {j1['phi_upper95']:.2f}); {j1['n_correct']} correct and {j1['n_mutants']} seeded wrong answers" if j1 and j2 else "pending") + "}")
g4 = next((c for g in gates if g["gate"] == "G4" for c in g["criteria"] if c["id"] == "NFR-007"), None)
out.append(r"\newcommand{\NfrSevenPooled}{" + tex(g4["evidence"] if g4 else "pending") + "}")
os.makedirs(os.path.join(ROOT, "docs/publication/gen"), exist_ok=True)
open(os.path.join(ROOT, "docs/publication/gen/results.tex"), "w").write("\n".join(out) + "\n")
print("docs/publication/gen/results.tex written:", len(out), "definitions")
